export const calculatePrice = (basePrice, months = 1) => {
  let discount = 0
  if (months >= 36) discount = 0.20 // 20% off for 36+ months
  else if (months >= 24) discount = 0.15 // 15% off for 24+ months
  else if (months >= 12) discount = 0.10 // 10% off for 12+ months

  return Math.round(basePrice * (1 - discount))
}
